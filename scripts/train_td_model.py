"""Fit the anytime-touchdown model from public/data/stats.json.

Offline research tool (needs scikit-learn); it is not part of any workflow.
Trains on every season before the latest, reports a holdout score on the
latest season, then refits on everything and writes src/lib/tdWeights.js.
Features must stay in sync with src/lib/tdModel.js.
"""
import json
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression

ROOT = Path(__file__).resolve().parents[1]
FEATURES = ["oppAvg", "oppLast3", "snapLast3", "rz0", "rz1", "rz2", "rz3", "rz4",
            "tdAvg", "tdGameRate", "isRB", "isTE", "isQB", "noRedZoneData"]


def mean(values):
    return sum(values) / len(values) if values else 0.0


def features(history, position):
    opp = [g.get("usage", {}).get("opportunities") or 0 for g in history]
    snaps = [g.get("usage", {}).get("offenseSnapRate") or 0 for g in history]
    rz = [g["scoringChances"] for g in history
          if isinstance(g.get("scoringChances"), list) and len(g["scoringChances"]) >= 5]
    tds = [g.get("stats", {}).get("scoredTDs") or 0 for g in history]
    return [mean(opp), mean(opp[-3:]), mean(snaps[-3:]),
            *[mean([r[i] or 0 for r in rz]) for i in range(5)],
            mean(tds), (sum(t > 0 for t in tds) + 1) / (len(tds) + 5),
            float(position in ("RB", "FB")), float(position == "TE"), float(position == "QB"), float(not rz)]


def rows(data):
    for player in data["players"]:
        if player["position"] not in ("QB", "RB", "FB", "WR", "TE"):
            continue
        games = sorted((g for g in player["games"] if g.get("seasonType", "REG") == "REG"),
                       key=lambda g: (g["season"], int(g["week"])))
        for index, game in enumerate(games):
            history = games[:index][-10:]
            if len(history) >= 3:
                yield game["season"], player["position"] == "QB", features(history, player["position"]), int((game["stats"].get("scoredTDs") or 0) > 0)


def main():
    data = json.loads((ROOT / "public/data/stats.json").read_text())
    seasons, qb, x, y = map(np.array, zip(*rows(data)))
    latest = seasons.max()
    train, test = (seasons < latest) & (seasons > seasons.min()), seasons == latest
    model = LogisticRegression(max_iter=5000).fit(x[train], y[train])
    predicted = model.predict_proba(x[test])[:, 1]
    holdout = {"season": int(latest), "games": int(test.sum()), "actualRate": round(float(y[test].mean()), 4),
               "brier": round(float(np.mean((predicted - y[test]) ** 2)), 4),
               "baseRateBrier": round(float(np.mean((y[train].mean() - y[test]) ** 2)), 4)}
    final = LogisticRegression(max_iter=5000).fit(x[seasons > seasons.min()], y[seasons > seasons.min()])
    weights = {"features": FEATURES, "coefficients": [round(float(c), 5) for c in final.coef_[0]],
               "intercept": round(float(final.intercept_[0]), 5), "holdout": holdout}
    (ROOT / "src/lib/tdWeights.js").write_text("// Generated by scripts/train_td_model.py\nexport default " + json.dumps(weights, indent=1) + ";\n")
    print(json.dumps(holdout))
    print("  quarterbacks: n=%d predicted=%.2f actual=%.2f" % (qb[test].sum(), predicted[qb[test]].mean(), y[test][qb[test]].mean()))
    for low, high in ((0, .1), (.1, .2), (.2, .3), (.3, .45), (.45, 1)):
        keep = (predicted >= low) & (predicted < high)
        if keep.any():
            print(f"  predicted {low:.2f}-{high:.2f}: n={keep.sum()} predicted={predicted[keep].mean():.2f} actual={y[test][keep].mean():.2f}")


if __name__ == "__main__":
    main()
