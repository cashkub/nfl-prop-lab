// Keeps a graded archive of DraftKings prop lines and re-measures, each run, how far
// the prop model should be trusted when it disagrees with the line.
// Uses only lines the odds workflow already saved; it never calls the odds API.
//   node scripts/calibrate_props.mjs [--seed <dir of old lines.json copies>]
import fs from 'node:fs';
import {estimateModelHitRate,blendWithMarket} from '../src/lib/stats.js';
import {playerKey,fairSideProbability} from '../src/lib/bookLine.js';

const ARCHIVE='public/data/prop-lines-archive.json',WEIGHTS='src/lib/propWeights.js';
const MIN_GRADED=300,MAX_WEIGHT=.6,DEFAULT_WEIGHT=.2,CAUTION=400;
const read=path=>JSON.parse(fs.readFileSync(path));
const archive=fs.existsSync(ARCHIVE)?read(ARCHIVE):{version:1,props:[]};
const byKey=new Map(archive.props.map(p=>[p.key,p]));

// 1. Remember the latest pregame line for every prop.
function remember(payload){
  for(const game of payload.games||[])for(const line of game.lines||[]){
    if(line.metric==='scoredTDs'||!Number.isFinite(line.over)||!Number.isFinite(line.under))continue;
    const seen=Date.parse(line.updated||game.checkedAt||0),kickoff=Date.parse(game.kickoff);
    if(!Number.isFinite(kickoff)||seen>=kickoff)continue;
    const key=[game.kickoff.slice(0,10),game.away,game.home,playerKey(line.player),line.metric].join('|');
    const previous=byKey.get(key);
    if(previous&&(previous.hit!==undefined||previous.seen>=seen))continue;
    byKey.set(key,{key,player:line.player,metric:line.metric,point:line.point,over:line.over,under:line.under,
      away:game.away,home:game.home,kickoff:game.kickoff,seen});
  }
}
const seed=process.argv.indexOf('--seed');
if(seed>0)for(const file of fs.readdirSync(process.argv[seed+1]))remember(read(process.argv[seed+1]+'/'+file));
remember(read('public/data/lines.json'));

// 2. Grade finished props and store the model's own (pre-market) chance for the over.
const stats=read('public/data/stats.json');
const players=new Map(stats.players.map(p=>[playerKey(p.name),p]));
for(const prop of byKey.values()){
  if(prop.hit!==undefined)continue;
  const player=players.get(playerKey(prop.player));
  if(!player)continue;
  const season=new Date(Date.parse(prop.kickoff)-6*3600000).getUTCFullYear();
  const games=player.games.filter(g=>g.season===season).sort((a,b)=>a.week-b.week);
  const played=games.find(g=>g.gameId?.includes(prop.home)&&g.gameId?.includes(prop.away));
  if(!played)continue;
  const history=games.filter(g=>g.week<played.week).slice(-10);
  if(history.length<4)continue;
  const actual=Number(played.stats[prop.metric]??0);
  prop.actual=actual;
  prop.hit=actual===prop.point?null:Number(actual>prop.point);
  prop.model=Number(estimateModelHitRate(history,prop.metric,prop.point,'over',{position:player.position}).raw.toFixed(4));
  prop.fair=Number(fairSideProbability(prop,'over',prop.point).toFixed(4));
}

// 3. Pick the trust weight that would have predicted those results best.
const graded=[...byKey.values()].filter(p=>p.hit===0||p.hit===1);
const loss=weight=>graded.reduce((sum,p)=>{
  const chance=blendWithMarket(p.model,p.fair,weight);
  return sum-Math.log(p.hit?chance:1-chance);
},0)/graded.length;
let weight=DEFAULT_WEIGHT,fitted=null;
if(graded.length>=MIN_GRADED){
  let best=Infinity;
  for(let w=0;w<=MAX_WEIGHT+1e-9;w+=.01){const value=loss(w);if(value<best){best=value;fitted=Number(w.toFixed(2));}}
  // A few hundred props cannot pin the weight down, so trust the fit only in proportion
  // to how much evidence there is. The weight grows toward the fit as weeks accumulate.
  weight=Number((fitted*graded.length/(graded.length+CAUTION)).toFixed(2));
}
const brier=w=>graded.length?Number((graded.reduce((sum,p)=>sum+(blendWithMarket(p.model,p.fair,w)-p.hit)**2,0)/graded.length).toFixed(4)):null;
const result={weight,fitted,graded:graded.length,brierLineOnly:brier(0),brierWithModel:brier(weight),updated:new Date().toISOString().slice(0,10)};

archive.props=[...byKey.values()].sort((a,b)=>a.key.localeCompare(b.key));
fs.writeFileSync(ARCHIVE,JSON.stringify(archive)+'\n');
fs.writeFileSync(WEIGHTS,`// Generated by scripts/calibrate_props.mjs. How far the prop model is trusted
// when it disagrees with the sportsbook's no-vig line (0 = all line, 1 = all model).
export default ${JSON.stringify(result)};
`);
console.log(`Prop calibration: ${archive.props.length} lines archived, ${graded.length} graded, weight ${weight}`,result);
